// Builds src/icons/paths.ts from the names in src/icons/icon-names.json.
// Source: Material Symbols Outlined, weight 400 (@material-symbols/svg-400, Apache 2.0).
// Add a name to icon-names.json first ("star-fill" for a filled icon), then run:
//   pnpm --filter @ttn/ui icons
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const svgDir = path.join(root, "node_modules/@material-symbols/svg-400/outlined");
const listFile = path.join(root, "src/icons/icon-names.json");
const outFile = path.join(root, "src/icons/paths.ts");

const names = [...new Set(JSON.parse(readFileSync(listFile, "utf8")))].sort();

const readPath = (name) => {
  let svg;
  try {
    svg = readFileSync(path.join(svgDir, `${name}.svg`), "utf8");
  } catch {
    throw new Error(`Unknown icon "${name}": no ${name}.svg in @material-symbols/svg-400/outlined`);
  }
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length !== 1) throw new Error(`Icon "${name}" has ${paths.length} paths; expected 1`);
  return paths[0];
};

const lines = names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readPath(name))},`);

writeFileSync(
  outFile,
  `// Generated by scripts/build-icons.mjs from icon-names.json. Do not edit by hand.
// Material Symbols Outlined, weight 400 (Apache 2.0). Paths use viewBox "0 -960 960 960".
export const ICON_PATHS = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`,
);

console.log(`Wrote ${names.length} icons to src/icons/paths.ts`);
